/**
 * عشوائيةٌ تصلح للأسرار — المحرّك المشترك لكل ما يُولَّد ويُحرَس في البرنامج.
 *
 * 🔴 لماذا ملف مستقل؟ لأن **العلّة نفسها ظهرت مرّتين**:
 *   · أكواد التفعيل — مفتاحٌ يُباع، كان يُولَّد بـ`Math.random()`.
 *   · كلمة سر حساب الموظف — اعتمادٌ يفتح جلسة، وكان يُولَّد بـ`Math.random()` أيضاً.
 * ونفس ما فُعل بترقيم المستندات (`sequenceNumber.ts` بعد أن تكرّر منطق الترقيم ثلاثاً):
 * يُوحَّد المحرّك في مكانٍ واحد محروس، وتبقى الملفات المتخصّصة أغلفةً باسم مجالها.
 * فمن يضيف سرّاً ثالثاً غداً يجد الأداة الصحيحة جاهزة بدل أن يبدأ من `Math.random`.
 *
 * ⚠️ العلّة التقنية بدقّة: `Math.random()` في V8 هو **xorshift128+** — مولّد سريع مصمَّم
 * للألعاب والرسوم، **لا للأسرار**، وحالته الداخلية قابلة للاستنتاج من مخرجاته (بحث منشور).
 * فمن رأى بعض مخرجاته يستطيع نظرياً توقّع ما بعدها — وهذا مقبول لمعرّف وثيقة، وكارثة
 * لمفتاحٍ أو كلمة سر.
 *
 * 📌 حدُّ الاستعمال: هذا للأسرار وحدها. معرّفات الوثائق (`genId`, `genAuditId`) ووسم
 * الجهاز في الترقيم تبقى على `Math.random` عن قصد — مطلوبها تفادي التصادم لا السرّية،
 * وتغييرها بلا سبب يزيد الكلفة بلا فائدة.
 */

/**
 * مصدر بايتات عشوائية.
 * يُمرَّر كمُعامل ليكون التوليد قابلاً للاختبار حتمياً — لا لتخفيف الحماية.
 */
export type RandomBytes = (n: number) => Uint8Array;

const cryptoBytes: RandomBytes = (n) => {
  const out = new Uint8Array(n);
  // `crypto` متاح في كل متصفح حديث وفي Electron — ولا بديل صامت له عمداً:
  // الفشل الصريح أسلم من العودة إلى Math.random بلا علم أحد.
  globalThis.crypto.getRandomValues(out);
  return out;
};

/**
 * اختيار محارف من أبجدية بلا تحيّز — **رفضُ العيّنة** لا قسمة الباقي.
 *
 * ⚠️ ولماذا الرفض وليس `byte % n`؟ لأن التحيّز يعتمد على طول الأبجدية:
 *   · ٣٢ حرفاً (أكواد التفعيل): ٢٥٦ = ٨×٣٢ تماماً ⟵ لا تحيّز في القسمة أصلاً.
 *   · ٣١ حرفاً (كلمة سر الموظف): ٢٥٦ = ٨×٣١ + ٨ ⟵ **الأحرف الثمانية الأولى تظهر
 *     أكثر من غيرها**، تحيّزٌ حقيقي صامت لا يكشفه اختبار عابر.
 * فلا نبني على مصادفةٍ في الطول. الرفض يبقى صحيحاً مهما تغيّرت الأبجدية.
 */
export function pickChars(
  alphabet: string,
  count: number,
  randomBytes: RandomBytes = cryptoBytes,
): string {
  const n = alphabet.length;
  if (n === 0 || count <= 0) return '';
  const limit = Math.floor(256 / n) * n;   // أكبر مضاعف للطول ضمن البايت
  const out: string[] = [];
  let guard = 0;
  while (out.length < count) {
    if (++guard > 64) throw new Error('تعذّر توليد عشوائية كافية');
    const batch = randomBytes(count - out.length + 8);
    for (const b of batch) {
      if (out.length >= count) break;
      if (b >= limit) continue;            // بايت في الذيل غير المتوازن ⟵ يُرفض
      out.push(alphabet[b % n]);
    }
  }
  return out.join('');
}
