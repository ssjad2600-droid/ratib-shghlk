import { Capacitor } from '@capacitor/core';

/**
 * رسالة تعذُّر الطباعة — تختلف باختلاف المنصّة.
 *
 * 🔴 العلّة: كل مسارات الطباعة الستّة تفتح نافذةً منبثقة (`window.open`) ثم تقول
 * عند فشلها: «تأكد من السماح بالنوافذ المنبثقة». وهذه نصيحةٌ صحيحة في المتصفّح،
 * و**مستحيلةُ التنفيذ داخل تطبيق الهاتف**: لا إعداد للنوافذ المنبثقة في WebView،
 * فيبحث التاجر عن خيارٍ لا وجود له، ثم يتّصل بالدعم لأن «الطباعة خربانة».
 *
 * 🎯 والصدق أنفع: الطباعة الحرارية وA4 مصمّمتان لطابعةٍ موصولة بالكمبيوتر —
 * فتقول الرسالة ذلك، وتدلّه على البديل المتاح فعلاً على هاتفه (التصدير والمشاركة).
 *
 * ⚠️ ومصدرٌ واحد لا ستّة: نصٌّ مكرّر في ستّة ملفات ينحرف عند أول تعديل، ويبقى
 * أحدها يقول للتاجر ما لا يستطيع فعله. (النمط نفسه في `writeGuard` و`saveFile`.)
 */

export const POPUP_BLOCKED_MESSAGE =
  'تعذّر فتح نافذة الطباعة، تأكد من السماح بالنوافذ المنبثقة';

export const PRINT_ON_PHONE_MESSAGE =
  'الطباعة غير متاحة في تطبيق الهاتف — الفواتير تُطبع من نسخة الكمبيوتر '
  + 'حيث الطابعة موصولة. تستطيع هنا تصدير البيانات ومشاركتها.';

/** الرسالة المناسبة للمنصّة الحالية. */
export function printWindowError(
  isNative: boolean = Capacitor.isNativePlatform(),
): string {
  return isNative ? PRINT_ON_PHONE_MESSAGE : POPUP_BLOCKED_MESSAGE;
}

/**
 * هل تُعرض أزرار الطباعة أصلاً؟
 *
 * تُستعمل في الواجهة لإخفاء الزرّ بدل تركه يُخطئ عند كل ضغطة — فزرٌّ يفشل دائماً
 * أسوأ من زرٍّ غائب.
 */
export function canPrint(isNative: boolean = Capacitor.isNativePlatform()): boolean {
  return !isNative;
}
