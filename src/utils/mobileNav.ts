/**
 * الشاشات المدعومة على الهاتف — نطاق «رفيق المالك».
 *
 * 🔴 لماذا مجموعةٌ مُعرَّفة لا «كل الشاشات»؟ البرنامج فيه ٢٢ شاشة صُمّمت لكمبيوترٍ
 * في محلّ: جداول بعشرة أعمدة، طباعة حرارية، مسدس باركود USB. حشرُها في ٣٧٥px
 * لا يُنتج تطبيق هاتف بل نسخةً مكسورة من تطبيق سطح مكتب — والتاجر الذي يفتح
 * «تسوية المخزون» على هاتفه فيجدها غير صالحة يحكم على التطبيق كلّه.
 *
 * فالهاتف هنا **رفيقٌ لا بديل**: صاحب المحل يتابع أرصدته وديونه وجرده وصندوقه
 * وهو خارج المحل. والبيع والطباعة يبقيان حيث صُمّما.
 *
 * ⚠️ وهذا لا يحذف شيئاً: الشاشات الأخرى تعمل كاملةً على الكمبيوتر واللوحي (فوق
 * ٧٦٨px تظهر القائمة الجانبية بكل بنودها). المُخفى هو مدخلها من شريط الهاتف فقط.
 */

/** الخمس الأكثر استعمالاً — تظهر في الشريط السفلي مباشرةً. */
export const MOBILE_PRIMARY = ['dashboard', 'invoices', 'products', 'customers', 'debts'] as const;

/** الباقي — خلف زرّ «المزيد». */
export const MOBILE_MORE = ['cashclosing', 'reports', 'settings', 'guide'] as const;

/**
 * 🔴 خمسة في الشريط لا ثمانية: على عرض ٣٧٥px يعطي الثمانيةُ ٤٧px للزرّ الواحد —
 * أضيق من حدّ اللمس الموصى به (٤٤px) بعد الحشو، وتسميةٌ بحجم ٧٫٥px لا تُقرأ.
 * خمسةٌ وزرّ «المزيد» تعطي ٦٢px لكلٍّ منها، وتسميةً بحجمٍ مقروء.
 */
export const MOBILE_SCREENS: readonly string[] = [...MOBILE_PRIMARY, ...MOBILE_MORE];

/** هل هذه الشاشة مدعومة على الهاتف؟ (`admin` تُضاف للمالك وحده خارج هذه القائمة) */
export const isMobileScreen = (id: string): boolean => MOBILE_SCREENS.includes(id);

/** هل الشاشة الحالية خلف زرّ «المزيد»؟ — لإبراز الزرّ حين تكون نشطة. */
export const isBehindMore = (id: string): boolean =>
  (MOBILE_MORE as readonly string[]).includes(id) || id === 'admin';

/**
 * تسميات قصيرة لشريط الهاتف.
 *
 * 🔴 مفهرسةٌ بالمعرّف لا بالنصّ: الفهرسة بالنصّ تنكسر بصمت عند أول تعديلٍ على
 * تسمية القائمة الجانبية، فيظهر الاسم الطويل مقصوصاً («الوصولات والفوا…»).
 *
 * والسبب: زرٌّ عرضه ~٦٢px لا يتّسع لـ«الوصولات والفواتير». والاسم الطويل يبقى
 * كما هو في القائمة الجانبية على الكمبيوتر — لا يُمسّ.
 */
const SHORT: Record<string, string> = {
  dashboard: 'الرئيسية',
  invoices: 'الفواتير',
  products: 'المخزون',
  customers: 'الزبائن',
  debts: 'الديون',
  cashclosing: 'الصندوق',
  reports: 'التقارير',
  settings: 'الإعدادات',
  guide: 'الدليل',
  admin: 'المالك',
};

/** يُعيد التسمية القصيرة، وإلا الطويلةَ منزوعةَ الرموز التعبيرية. */
export function shortLabel(id: string, fallback: string): string {
  return SHORT[id] ?? fallback.replace(/[\p{Extended_Pictographic}️]/gu, '').trim();
}
