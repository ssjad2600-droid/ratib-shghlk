import { where, orderBy, QueryConstraint } from 'firebase/firestore';
import { localDateKey } from './dateLocal';

/**
 * نافذة زمنية على استعلامات Firestore — الفلترة على **الخادم** لا في المتصفح.
 *
 * 🔴 المشكلة التي تحلّها: كل شاشة كانت تفتح اشتراكاً على المجموعة **كاملةً**. محل يعمل
 * سنتين (~١٥ ألف فاتورة) كان سيُحمّلها كلها في كل جلسة — إقلاع بطيء، باقة إنترنت
 * تُستهلك، وفاتورة Firestore تُحاسَب بعدد الوثائق المقروءة فتلتهم أرباح الاشتراكات.
 *
 * القيد على حقل **واحد** (`date`) بصيغة YYYY-MM-DD القابلة للمقارنة النصّية ⇒
 * **لا يحتاج فهرساً مركّباً** في Firestore. أي جمعه مع مساواة أخرى (مثل createdByUid
 * في جلسة الموظف) سيتطلّب فهرساً — ولهذا لا نستخدمه في مسارات الموظف.
 *
 * ⚠️ متى **لا** تُستخدم: حيث تكون الصحّة رهينة السجل الكامل — النسخة الاحتياطية،
 * وسجل زبون بعينه، والديون/الأقساط المرتبطة بفواتير قديمة. تلك تبقى كاملة عمداً.
 */

/** مفتاح يوم قبل n يوماً من اليوم (بالتوقيت المحلي — لا UTC). */
export function daysAgoKey(days: number): string {
  const d = new Date();
  d.setDate(d.getDate() - days);
  return localDateKey(d);
}

/**
 * قيود نافذة على حقل `date`. القائمة مصفوفة جديدة في كل نداء، فيجب **تذكيرها**
 * (useMemo) عند التمرير إلى useCollection وإلا أُعيد الاشتراك في كل رندر.
 */
export function windowConstraints(fromKey: string): QueryConstraint[] {
  return [where('date', '>=', fromKey)];
}

/** نافذة بعدد أيام + ترتيب تنازلي (الأحدث أولاً) — يستفيد من نفس الفهرس المفرد. */
export function recentConstraints(days: number): QueryConstraint[] {
  return [where('date', '>=', daysAgoKey(days)), orderBy('date', 'desc')];
}

