/**
 * معرّف مستند شبه فريد: طابع زمني (ملّي ثانية) + لاحقة عشوائية قصيرة.
 *
 * 🔴 لماذا: `String(Date.now())` وحده يتصادم إذا أنشأ جهازان (مالك + موظف، أو موظفان) وثيقة
 * في نفس الملّي ثانية ⇒ استبدال صامت لإحدى الوثيقتين. اللاحقة العشوائية تزيل هذا الاحتمال عملياً.
 *
 * يبقى الطابع الزمني في **المقدمة** حتى يظل `parseInt(id)` (المستخدم كبديل createdAt وفترة السماح
 * في الفواتير) يستخرج الطابع الصحيح — parseInt يتوقف عند أول محرف غير رقمي.
 */
export const genId = (): string =>
  `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
