/**
 * معرّف ثابت مشتقّ من محتوى السجل — لا من لحظة إنشائه.
 *
 * 🔴 لماذا؟ الاستيراد الجماعي كان يولّد `cust_${Date.now()}_${idx}`. فلو تعثّرت العملية
 * (انقطاع إنترنت، إغلاق النافذة) وأعاد التاجر المحاولة بالملف نفسه، تولّدت **معرّفات
 * جديدة كلياً** فدخل كل زبون مرتين. ٥٠٠ زبون يصيرون ألفاً، ولا شيء يشير إلى الخطأ إلا
 * قائمة صارت ضِعف طولها.
 *
 * والمعرّف المشتقّ من المحتوى يجعل إعادة الاستيراد **تصحيحاً لا تكراراً**: نفس الصف
 * يعطي نفس المعرّف، فيُكتب فوق نفسه بدل أن يُضاف بجانبه.
 *
 * ⚠️ لا يُستعمل هذا للفواتير ولا للتسديدات: هناك تكرار الصف **حدث حقيقي منفصل**
 *   (بيعتان بنفس المبلغ لنفس الزبون في اليوم نفسه واردتان)، فيلزمها معرّف فريد لا ثابت.
 *   هذا للسجلات التي يعرّفها محتواها: زبون باسمه وهاتفه، منتج بباركوده.
 */

/**
 * تجزئة FNV-1a — ٣٢ بت، بلا اعتماديات، ونتيجتها ثابتة عبر الأجهزة والجلسات.
 * لا تُستعمل للأمان إطلاقاً؛ غرضها الوحيد اشتقاق مفتاح قصير مستقرّ من نص.
 */
function fnv1a(text: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    // h *= 16777619 بحساب ٣٢ بت دون تجاوز الدقة
    h = (h + ((h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24))) >>> 0;
  }
  return h >>> 0;
}

/**
 * `stableId('cust', 'المفتاح')` ⇒ مثل `cust_1a2b3c4d`.
 *
 * يُضاف طول النص إلى المفتاح لتقليل التصادم بين نصوص قصيرة متشابهة، ويُطبَّع النص
 * (قصّ وتوحيد حالة الأحرف) كي لا يُنتج «علي » و«علي» معرّفين مختلفين.
 */
export function stableId(prefix: string, key: string): string {
  const normalized = String(key ?? '').trim().toLowerCase().replace(/\s+/g, ' ');
  const hash = fnv1a(`${normalized}|${normalized.length}`).toString(36).padStart(7, '0');
  return `${prefix}_${hash}`;
}
