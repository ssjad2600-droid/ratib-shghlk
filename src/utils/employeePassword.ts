/**
 * كلمة السر المؤقتة لحساب الموظف — غلافٌ رقيق فوق {@link ./secureRandom}.
 *
 * 🔴 العلّة التي وُلد منها هذا الملف:
 *
 * ```ts
 * const chars = 'abcdefghjkmnpqrstuvwxyz23456789';
 * for (let i = 0; i < 8; i++) out += chars[Math.floor(Math.random() * chars.length)];
 * ```
 *
 * هذه كانت داخل `EmployeeManagement.tsx` مباشرةً. وهي **نفس علّة أكواد التفعيل** لكن على
 * ما هو أخطر: الكود قفلٌ يُشترى، وكلمة السر **مفتاحٌ يفتح جلسة في Firebase Auth**.
 *
 * ولماذا يهمّ هذا في هذا البرنامج تحديداً؟ لأن أغلى ما فيه للمالك هو **سجل التدقيق**:
 * «من فعل ماذا ومتى». ومن انتحل حساب موظف يبيع باسمه، فيصير السجل — وهو الدليل — شهادةَ
 * زور. أي أن ضعف المولّد لا يهدّد حساباً واحداً بل يهدّم الميزة التي تُباع.
 *
 * ⚖️ وبلا مبالغة: الجلسة تُنشئ موظفاً أو اثنين عادةً، فالعيّنة المتاحة للمهاجم ضئيلة
 * والاستنتاج من مخرجات مقتطعة عملٌ غير يسير. لكنه **الأداة الخاطئة** لهذا الغرض،
 * والصحيحة متاحة في سطر واحد.
 */

import { pickChars, RandomBytes } from './secureRandom';

/**
 * أبجدية كلمة السر: حروف صغيرة وأرقام، **بلا i l o 0 1**.
 *
 * الاستبعاد مقصود ومحفوظ كما كان: المالك يقرأ الكلمة من الشاشة ويُمليها على الموظف أو
 * يكتبها له على ورقة. و`l` مع `1`، و`o` مع `0`، تُقرأ خطأً فيفشل الدخول ويتّصل بك.
 */
export const PASSWORD_ALPHABET = 'abcdefghjkmnpqrstuvwxyz23456789';

/**
 * الطول: ١٠ محارف.
 *
 * كان ٨ ⟵ ٣١⁸ ≈ ٨٥٢ مليار احتمال، وهو ضعيفٌ لكلمة سرٍّ **دائمة** لا تنتهي صلاحيتها
 * ولا يُلزَم أحد بتغييرها. و١٠ ⟵ ٣١¹⁰ ≈ ٨٢٠ **تريليون** (أقوى ٩٦١ ضعفاً) وتبقى قصيرة
 * بما يكفي لإملائها. زيادتها لا تكلّف المالك شيئاً: الكلمة تُولَّد له وزرّ النسخ موجود.
 */
export const PASSWORD_LENGTH = 10;

/**
 * كلمة سر مؤقتة عشوائية من مصدر تشفيري بلا تحيّز.
 *
 * ملاحظة: خانة كلمة السر في الشاشة تبقى **قابلة للتحرير** — للمالك أن يكتب كلمته الخاصة
 * إن شاء، وهذا سلوك قائم لا يمسّه هذا الملف. غايته أن يكون **الافتراضي** قوياً.
 */
export function generateEmployeePassword(randomBytes?: RandomBytes): string {
  return pickChars(PASSWORD_ALPHABET, PASSWORD_LENGTH, randomBytes);
}
