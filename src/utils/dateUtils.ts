/**
 * تاريخ اليوم المحلي 'yyyy-mm-dd' — مصدر واحد لكل الشاشات الكاتبة (فواتير/مصاريف/تسديدات).
 *
 * 🔴 حرج: لا تستخدم new Date().toISOString() لأنها بتوقيت UTC. العراق UTC+3، فأي عملية
 * بين منتصف الليل و٣ فجراً كانت تُسجَّل بتاريخ الأمس بينما التقارير وتقفيل الصندوق يحسبان
 * باليوم المحلي — فتسقط عمليات الفجر من يومها. هذه الدالة تبني التاريخ من المكوّنات المحلية.
 */
export const todayISO = (): string => {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
};

/**
 * معرّف مستند فريد عملياً: طابع زمني + ذيل عشوائي — يمنع تصادم String(Date.now()) عند
 * إنشاء وثيقتين في نفس الملّي ثانية (جهازان، أو ضغط سريع). يبقى قابلاً للتحليل الرقمي
 * (parseInt يتوقف عند '_') فلا يكسر منطق فترة السماح المعتمد على parseInt(id) كاحتياط.
 */
export const makeId = (): string =>
  `${Date.now()}_${Math.random().toString(36).slice(2, 8)}`;
