/**
 * التراجع عن قيدٍ أثّر في المخزون — آلية واحدة لثلاث شاشات: التسوية، الصلاحية، النقل.
 *
 * 🔴 لماذا هذا بندٌ يمسّ المال:
 * التاجر أراد تسجيل تلف ١٠ فكتب ١٠٠. لا سبيل اليوم للتراجع، فيصحّحها بقيدٍ ثانٍ
 * «إضافة ٩٠». والنتيجة في إحصاءات التسوية: `lostUnits = ١٠٠` و`addedUnits = ٩٠`،
 * وبطاقة «قيمة الخسارة» تعرض ثمن ١٠٠ قطعة **إلى الأبد**. والإضافة لا تُخصم من الخسارة
 * — عمداً وبحقّ، لأن الإضافة الحقيقية (مرتجع، جرد بالزيادة) حدثٌ مستقلّ لا تصحيح.
 * فخطأٌ مطبعيٌّ واحد يُضخّم خسائر التاجر المعلنة بلا رجعة، وهو يقرأ الرقم ويبني عليه.
 *
 * ⚖️ والمبدأ الحاكم: **التراجع ليس حذفاً**.
 * حذف القيد يُخفي أن الخطأ وقع، وهو بالضبط ما وُجد السجل لكشفه. فالقيد يبقى ويُختم
 * «متراجَع عنه»، ويُولَد قيدٌ مضادّ مربوط به. النتيجة:
 *   · **التاريخ يبقى صادقاً** — من سجّل، ومن تراجع، ومتى.
 *   · **الإحصاءات تستثني الطرفين** — لأنهما معاً يساويان لا شيء.
 *   · **المخزون يعود بفارقٍ لا بقيمة مطلقة** — فيبقى آمناً أوفلاين ومع بيعٍ متزامن.
 *
 * وقاعدة الاستثناء واحدة لا تقبل السهو: الإحصاء يستثني، **والسجل يعرض**. إخفاء القيد
 * المتراجَع عنه من السجل يعيدنا إلى الحذف من الباب الخلفي.
 */

/** كل سجل قابل للتراجع يحمل طرفَي الرابط — كلاهما اختياري وصامت. */
export interface Reversible {
  id: string;
  /** معرّف القيد المضادّ الذي ألغى هذا القيد. وجوده = هذا القيد متراجَع عنه. */
  reversedById?: string;
  /** معرّف القيد الأصلي الذي جاء هذا القيد ليُلغيه. وجوده = هذا القيد نفسه تراجُع. */
  reversalOfId?: string;
}

export const isReversed = (r: Reversible): boolean => !!r.reversedById;
export const isReversal = (r: Reversible): boolean => !!r.reversalOfId;

/** هل يدخل هذا القيد في حساب الخسائر والقيم؟ الطرفان معاً يساويان لا شيء. */
export const countsInStats = (r: Reversible): boolean => !isReversed(r) && !isReversal(r);

/** يستثني كِلا طرفَي التراجع — للإحصاءات وحدها، لا للسجل. */
export const activeOnly = <T extends Reversible>(records: T[]): T[] => records.filter(countsInStats);

/**
 * شكلٌ بسيط لا اتحادٌ مميَّز عمداً: `strict` معطَّل في tsconfig هذا المشروع، ومعه
 * `strictNullChecks`، فتضييق الاتحادات المميَّزة لا يعمل — و`check.reason` بعد `!check.ok`
 * يصير خطأ ترجمة. النوع المسطّح يعمل هنا كما هو.
 */
export interface ReversalCheck { ok: boolean; reason: string }

const OK: ReversalCheck = { ok: true, reason: '' };

/**
 * هل يجوز التراجع عن هذا القيد؟
 *
 * المنعان الأساسيان يمنعان فساداً حقيقياً لا إزعاجاً:
 *  · **المتراجَع عنه مرّتين** يُعيد المخزون مرّتين — بضاعةٌ تُخلق من العدم.
 *  · **التراجع عن تراجع** سلسلةٌ لا تنتهي ومعناها الحقيقي «أعد تسجيل القيد الأصلي»،
 *    وهو ما يجب أن يفعله التاجر صراحةً لا ضمناً.
 */
export function canReverse(record: Reversible): ReversalCheck {
  if (isReversed(record)) {
    return { ok: false, reason: 'تمّ التراجع عن هذا القيد سابقاً — التراجع مرّتين يُعيد البضاعة مرّتين.' };
  }
  if (isReversal(record)) {
    return {
      ok: false,
      reason: 'هذا القيد نفسه تراجُعٌ عن قيد آخر. إن أردت إعادة الأثر فسجّله قيداً جديداً صريحاً.',
    };
  }
  return OK;
}

/** ما يُكتب على القيد الأصلي لحظة التراجع. */
export const markReversedUpdate = (reversalId: string): Record<string, unknown> => ({
  reversedById: reversalId,
});

/**
 * صياغة سبب القيد المضادّ — تشرح نفسها في السجل بعد سنة.
 * @param originalReason سبب القيد الأصلي (يُقتبس كي لا يضيع السياق)
 */
export const reversalReason = (originalReason: string, note?: string): string => {
  const base = `تراجُع عن قيد سابق: ${originalReason || 'بلا سبب مكتوب'}`;
  return note?.trim() ? `${base} — ${note.trim()}` : base;
};
