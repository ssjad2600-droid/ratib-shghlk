import { Capacitor } from '@capacitor/core';

/**
 * نسخة الهاتف **للاطّلاع فقط** — لا بيع، ولا إصدار فواتير، ولا أي كتابة.
 *
 * 🎯 القرار: الهاتف رفيقٌ يُطالِع ما يصدر من حساب الكمبيوتر — الفواتير والأرباح
 * والتفاصيل المالية. والكتابة كلّها تبقى حيث صُمّمت: على الكمبيوتر.
 *
 * 🔴 ولماذا حارسٌ في وقت التشغيل لا إخفاءٌ بـCSS؟ لأن `md:hidden` حدٌّ **بعرض
 * الشاشة** لا بالمنصّة: اللوحي يتجاوزه، وتدوير الهاتف قد يتجاوزه، وزرٌّ مخفيٌّ
 * بصرياً يبقى في الصفحة قابلاً للضغط برمجياً. وإخفاءُ زرٍّ ليس منعَ عملية.
 *
 * فالطبقات ثلاث، والأخيرة وحدها هي الحقيقية:
 *   ١) التنقّل — شاشات الكتابة لا مدخل لها من شريط الهاتف (`mobileNav.ts`).
 *   ٢) الواجهة — أزرار الكتابة لا تُعرض.
 *   ٣) **الحارس** — كل مسار كتابة يُرفَض هنا مهما وصل إليه المستخدم.
 *
 * ويحرسه مسحٌ في `viewOnly.test.ts` يرفض أي مسار كتابةٍ جديد بلا حارس.
 */

/**
 * الرسالة الواحدة — نصٌّ واحد لا يفترق.
 *
 * 🔴 مصدرٌ واحد لا عشرة: نصٌّ مكرّر في كل شاشة ينحرف عند أول تعديل، فيبقى أحدها
 * يقول للتاجر ما لا يطابق البقية. (النمط نفسه في `printSupport` و`writeGuard`.)
 */
export const VIEW_ONLY_MESSAGE =
  'نسخة الهاتف للاطّلاع فقط — هذه العملية تُنفَّذ من نسخة الكمبيوتر.';

/** خطأٌ مميَّز كي تفرّقه الشاشات عن أخطاء الشبكة والصلاحيات. */
export class ViewOnlyError extends Error {
  constructor(message: string = VIEW_ONLY_MESSAGE) {
    super(message);
    this.name = 'ViewOnlyError';
  }
}

/**
 * هل نحن في نسخة الهاتف؟
 *
 * ⚠️ المعيار **المنصّة** لا عرض الشاشة:
 *   · `isNativePlatform()` صحيحةٌ داخل تطبيق أندرويد/iOS وحده.
 *   · نسخة الكمبيوتر (Electron) ليست منصّةَ Capacitor ⟶ تُعيد `false`، فلا تتأثّر.
 *   · ونافذة متصفّحٍ ضيّقة على الكمبيوتر تبقى قابلةً للكتابة — وهو المطلوب:
 *     التاجر الذي يُصغّر نافذته لا يفقد برنامجه.
 *
 * والمُعامل مُمرَّرٌ لا مقروءٌ داخلياً كي يُختبر السلوك على المنصّتين بلا محاكاة.
 */
export function isViewOnly(isNative: boolean = Capacitor.isNativePlatform()): boolean {
  return isNative;
}

/**
 * يرمي إن كانت الكتابة ممنوعة — يُستدعى في **رأس** كل مسار كتابة.
 *
 * 🔴 يرمي ولا يُعيد `false` صامتاً: الرمي يوقف المسار كلّه بلا اعتمادٍ على أن
 * يتذكّر كلُّ نداءٍ فحصَ القيمة المُعادة. ونسيانُ الفحص هو بالضبط ما يجعل
 * الحرّاس الصامتة تمرّ.
 */
export function assertWritable(isNative?: boolean): void {
  if (isViewOnly(isNative)) throw new ViewOnlyError();
}

/** هل هذا الخطأ سببه وضع الاطّلاع؟ — لتعرضه الشاشة رسالةً هادئة لا «تعذّر الحفظ». */
export const isViewOnlyError = (e: unknown): boolean =>
  e instanceof ViewOnlyError || (e instanceof Error && e.name === 'ViewOnlyError');
