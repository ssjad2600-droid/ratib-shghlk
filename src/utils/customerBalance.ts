/**
 * قرار تعديل رصيد الزبون — منطق نقيّ مفصول عن الواجهة كي يُختبر.
 *
 * 🔴 العلّة التي وُلد منها هذا الملف: شاشة الزبائن كانت تحفظ الرصيد **قيمةً مطلقة** من
 * اللقطة التي حُمّلت وقت فتح النموذج. فمن يفتح ملف زبون ليصحّح عنوانه، ويبيع الكاشير
 * لنفس الزبون بالدين في تلك الدقائق، يمسح بحفظه ما أضافه البيع. دَينٌ يختفي بلا رسالة،
 * والتاجر لم يلمس خانة الرصيد أصلاً — وهذا أخبث ما في العلّة.
 *
 * القاعدة هنا ثلاث حالات لا رابع لها:
 *   • لم يُغيَّر ما في الخانة  ⇒ **لا يُمسّ الرصيد إطلاقاً** (الحالة الغالبة).
 *   • غُيّر ولم يتغيّر الرصيد من مكان آخر ⇒ يُطبَّق الفرق بـ`increment` فيتراكب بأمان.
 *   • غُيّر وتغيّر الرصيد أيضاً ⇒ **نسأل التاجر**، ولا نكتب فوق شيء بصمت.
 */

export type BalanceAction =
  /** لا تكتب الرصيد إطلاقاً — التاجر لم يقصد تعديله. */
  | { kind: 'skip' }
  /** طبّق هذا الفرق بـ increment — آمن أوفلاين ويتراكب مع الكتابات المتزامنة. */
  | { kind: 'apply'; delta: number }
  /** تعارض: اسأل التاجر أولاً. `deltaIfForced` هو ما يُطبَّق لو أصرّ على قيمته. */
  | { kind: 'conflict'; loaded: number; live: number; typed: number; deltaIfForced: number };

export interface BalanceDecisionInput {
  /** الرصيد لحظة فتح النموذج. */
  loaded: number;
  /** الرصيد الآن في البيانات الحيّة (قد يكون تغيّر أثناء التعديل). */
  live: number;
  /** ما كتبه التاجر في الخانة بعد تحليله رقماً. */
  typed: number;
}

/** يقرّر ما يُفعل برصيد الزبون عند حفظ التعديل. لا يكتب شيئاً — يقرّر فقط. */
export function decideBalanceWrite({ loaded, live, typed }: BalanceDecisionInput): BalanceAction {
  const l = Math.round(loaded);
  const v = Math.round(live);
  const t = Math.round(typed);

  // الخانة كما هي ⇒ التاجر جاء لتعديل الاسم أو العنوان، لا المال. لا نلمسه.
  if (t === l) return { kind: 'skip' };

  // الخانة تغيّرت والرصيد الحيّ ما زال كما فتحناه ⇒ الفرق آمن ويساوي ما كتبه بالضبط
  if (v === l) return { kind: 'apply', delta: t - l };

  // كلاهما تغيّر ⇒ لا نُرجّح أحدهما على الآخر من عندنا
  return { kind: 'conflict', loaded: l, live: v, typed: t, deltaIfForced: t - v };
}
